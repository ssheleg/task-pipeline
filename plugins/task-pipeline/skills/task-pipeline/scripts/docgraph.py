#!/usr/bin/env python3
"""docgraph: a project's documentation as a graph of linked nodes, the starter pack.

The starter pack («пакет новичка») is the smallest graph that is useful on the first
day: what the project is, its decisions, its scenarios, which document links to which,
and a search whose every hit is a verbatim passage at `path#La-Lb`. No model, no
network, no dependency beyond the Python standard library.

    docgraph.py init     [--root R]            write the pack, build, report (idempotent)
    docgraph.py build    [--root R]            rebuild the derived graph and the map
    docgraph.py check    [--root R] [--json] [--no-write]  exit 1 on a broken link or an expired fact
    docgraph.py heal     [--root R] [--fix]    find broken links, stale facts, orphans; --fix repairs
    docgraph.py prune    [--root R] [--apply]  retired and superseded docs; --apply moves them to docs/archive/
    docgraph.py search   QUERY [--root R] [-k N] [--json]   ranked passages with their lines
    docgraph.py cite     QUOTE PATH [--root R]  exit 0 only when QUOTE stands verbatim in PATH
    docgraph.py neighbours ID [--root R] [--json]  the node's edges both ways
    docgraph.py detect   [--root R] [--json]   is the documentation agent-ready? (hidden refactoring)
    docgraph.py refactor-note WHAT --did DONE [--task T] [--root R]  one row in docs/refactor-backlog.md

The graph's shape is `knowledge-graph/1`, profile `starter`: the node and edge fields of
the agents database's knowledge-graph design (D5), the same file other graphs map onto
(references/doc-graph.md, "One format"). Nodes {id, kind, area, title, pointer, status,
source_at}; edges {src, dst, kind, basis, provenance}. Markdown stays the source of
truth: the graph is derived (`.docgraph/graph.json`, git-ignored) and rebuilt in a
second; only the config, the map and the refactoring backlog are committed.

Exit codes: 0 clean, 1 a finding that fails the check (or a quote not found), 2 usage.
"""
