import datetime
import json
import math
import os
import re
import shutil
import subprocess
import sys

sys.dont_write_bytecode = True

SCHEMA = "knowledge-graph/1"
PROFILE = "starter"
CONFIG_REL = "docs/graph/docgraph.json"
MAP_REL = "docs/graph/MAP.md"
README_REL = "docs/graph/README.md"
BACKLOG_REL = "docs/refactor-backlog.md"
INDEX_DIR = ".docgraph"
GENERATED = "<!-- generated by docgraph: edit the documents it reads, not this file -->"
SKIP_DIRS = {".git", "node_modules", ".docgraph", "graphify-out", ".venv", "venv", "dist",
             "build", ".next", "target", "coverage", "__pycache__", ".task-pipeline",
             ".worktrees", "vendor"}

DEFAULT_CONFIG = {
    "schema": "docgraph-config/1",
    "graph": SCHEMA,
    "profile": PROFILE,
    "include": ["*.md", "docs/**/*.md"],
    "exclude": ["docs/archive/**", "CHANGELOG.md"],
    "entry": ["README.md", "AGENTS.md", "CLAUDE.md", "docs/graph/MAP.md"],
    "stale_days": 90,
    # Dated records cite the tree as it was: their findings are counted, never failed.
    "history": ["CHANGELOG.md", "**/HANDOFF.md", "docs/reports/**", "docs/evidence/**"],
    "areas": {
        "decisions": ["docs/adr/", "docs/decisions", "docs/DECISIONS", "decisions.md"],
        "scenarios": ["docs/ux/", "scenarios.md"],
        "reports": ["docs/reports/"],
        "backlog": ["backlog.md", "refactor-backlog.md", "open-questions.md"],
    },
}

# An id the documents define and cite: D-12, B-034, OQ-3, ADR-0001, S-12, R-001.
ID = re.compile(r"\b((?:ADR|DEC|OQ|SC|SCN|REQ|D|B|S|R|F|L|Q)-\d{1,5})\b")
ID_KIND = {"ADR": "decision", "DEC": "decision", "D": "decision", "B": "backlog",
           "R": "backlog", "OQ": "question", "Q": "question", "S": "scenario",
           "SC": "scenario", "SCN": "scenario", "REQ": "request", "F": "feature", "L": "lesson"}
LINK = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
CITATION = re.compile(r"`([A-Za-z0-9_./-]+\.[A-Za-z0-9]+):(\d+)(?:-(\d+))?`")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
RETIRED = {"superseded", "retired", "archived", "deprecated", "obsolete"}
BANNER = re.compile(r"^\s*>?\s*\**\s*(superseded|retired|deprecated|obsolete|устарел|заменён|заменен)\b",
                    re.I)
PASSAGE_MAX = 1500


# ---------------------------------------------------------------- files and config

def die(msg, code=2):
    print(f"docgraph: {msg}", file=sys.stderr)
    sys.exit(code)


def load_config(root):
    path = os.path.join(root, CONFIG_REL)
    cfg = json.loads(json.dumps(DEFAULT_CONFIG))
    if os.path.isfile(path):
        try:
            with open(path, encoding="utf-8") as fh:
                cfg.update(json.load(fh))
        except (OSError, ValueError) as exc:
            die(f"{CONFIG_REL} is not readable JSON: {exc}")
    return cfg


def _glob_match(rel, pattern):
    if pattern.endswith("/**"):
        return rel.startswith(pattern[:-3] + "/")
    if "/**/" in pattern:
        head, tail = pattern.split("/**/", 1)
        if not rel.startswith(head + "/"):
            return False
        return _glob_match(os.path.basename(rel), tail) or _glob_match(rel[len(head) + 1:], tail)
    if "/" not in pattern:
        if "/" in rel:
            return False
        return re.fullmatch(re.escape(pattern).replace(r"\*", "[^/]*"), rel) is not None
    return re.fullmatch(re.escape(pattern).replace(r"\*", "[^/]*"), rel) is not None


def documents(root, cfg):
    """Every Markdown file the config includes, repo-relative, sorted."""
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        for name in filenames:
            if not name.endswith(".md"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), root).replace(os.sep, "/")
            if rel == MAP_REL:
                continue
            if any(_glob_match(rel, p) for p in cfg.get("exclude", [])):
                continue
            if any(_glob_match(rel, p) for p in cfg.get("include", [])):
                out.append(rel)
    return sorted(out)


def read(root, rel):
    try:
        with open(os.path.join(root, rel), encoding="utf-8") as fh:
            return fh.read()
    except (OSError, UnicodeDecodeError):
        return None


def git(root, *args):
    try:
        r = subprocess.run(["git", "-C", root, *args], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout if r.returncode == 0 else None


def last_changed(root, rels):
    """{path: YYYY-MM-DD} from one git log; the file's mtime outside a checkout."""
    dates = {}
    log = git(root, "log", "--format=%x00%cs", "--name-only", "--", *rels) if rels else None
    if log:
        day = None
        for line in log.splitlines():
            if line.startswith("\x00"):
                day = line[1:]
            elif line and day and line not in dates:
                dates[line] = day
    for rel in rels:
        if rel not in dates:
            try:
                ts = os.path.getmtime(os.path.join(root, rel))
                dates[rel] = datetime.date.fromtimestamp(ts).isoformat()
            except OSError:
                dates[rel] = None
    return dates


def front_matter(text):
    m = FRONT.match(text)
    if not m:
        return {}
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t", "-")):
            k, v = line.split(":", 1)
            meta[k.strip().lower()] = v.strip().strip("\"'")
    return meta


def area_of(rel, cfg):
    for area, prefixes in cfg.get("areas", {}).items():
        for p in prefixes:
            if rel.startswith(p) or os.path.basename(rel) == p or rel == p:
                return area
    return "docs"


def title_of(text, rel):
    for line in text.splitlines():
        m = HEADING.match(line)
        if m:
            return m.group(2).strip()
    return os.path.basename(rel)


def first_paragraph(text):
    body = FRONT.sub("", text, count=1)
    para = []
    for line in body.splitlines():
        s = line.strip()
        if not s:
            if para:
                break
            continue
        if s.startswith(("#", "<!--", "[!", "!", "|", "```", ">", "---")) or s.startswith("[!["):
            if para:
                break
            continue
        para.append(s)
    return " ".join(para)


# ---------------------------------------------------------------- passages and search

def passages(rel, text):
    """Sections cut at headings, then at blank lines past PASSAGE_MAX: {path, a, b, title, text}."""
    lines = text.splitlines()
    out, start, title, buf = [], 1, title_of(text, rel), []

    def flush(end):
        body = "\n".join(buf).strip()
        if body:
            out.append({"path": rel, "a": start, "b": end, "title": title, "text": body})

    for i, line in enumerate(lines, 1):
        m = HEADING.match(line)
        size = sum(len(x) + 1 for x in buf)
        if m or (not line.strip() and size > PASSAGE_MAX):
            flush(i - 1)
            buf, start = [], i
            if m:
                title = m.group(2).strip()
        buf.append(line)
    flush(len(lines))
    return out


_RU_END = sorted("ами ями ого его ому ему ыми ими ая яя ое ее ой ей ий ый ых их ую юю ом ем ам ям ах ях ов ев "
                 "ть ет ит ут ют ат ят ешь ишь ние ния нию ности ость а я о е и ы у ю ь".split(),
                 key=len, reverse=True)
_EN_END = ("ations", "ation", "ings", "ing", "ers", "ies", "ied", "es", "ed", "er", "ly", "s")


def stem(word):
    w = word.lower().replace("ё", "е")
    if re.search("[а-я]", w):
        for end in _RU_END:
            if w.endswith(end) and len(w) - len(end) >= 3:
                return w[: -len(end)]
        return w
    for end in _EN_END:
        if w.endswith(end) and len(w) - len(end) >= 3:
            return w[: -len(end)]
    return w


def tokens(text):
    return [stem(t) for t in re.findall(r"[\w][\w-]*", text.lower()) if len(t) > 1]


def search(graph, query, k=5):
    docs = graph.get("passages", [])
    q = tokens(query)
    q_ids = set(ID.findall(query))
    if not docs or not (q or q_ids):
        return []
    toks = [tokens(p["title"] + "\n" + p["text"]) for p in docs]
    n = len(docs)
    avg = sum(len(t) for t in toks) / n or 1
    df = {}
    for t in toks:
        for w in set(t):
            df[w] = df.get(w, 0) + 1
    scored = []
    for p, t in zip(docs, toks):
        tf = {}
        for w in t:
            tf[w] = tf.get(w, 0) + 1
        s = 0.0
        for w in set(q):
            if w in tf:
                idf = math.log(1 + (n - df[w] + 0.5) / (df[w] + 0.5))
                s += idf * tf[w] * 2.2 / (tf[w] + 1.2 * (0.25 + 0.75 * len(t) / avg))
        if q_ids & set(ID.findall(p["text"])):
            s += 5.0
        if s > 0:
            scored.append((s, p))
    scored.sort(key=lambda x: (-x[0], x[1]["path"], x[1]["a"]))
    return [dict(p, score=round(s, 3), pointer=f"{p['path']}#L{p['a']}-L{p['b']}") for s, p in scored[:k]]


def norm_ws(text):
    return re.sub(r"\s+", " ", text).strip()


def cite(root, quote, rel):
    text = read(root, rel)
    if text is None:
        return None
    q = norm_ws(quote)
    if len(q) < 12:
        return None
    flat = norm_ws(text)
    if q not in flat:
        return None
    # The line the quote starts on, for the pointer.
    first = q.split(" ")[0]
    lines = text.splitlines()
    for i, line in enumerate(lines, 1):
        if first in line:
            window = norm_ws("\n".join(lines[i - 1:i + q.count(" ") + 2]))
            if q in window:
                return i
    return 1


# ---------------------------------------------------------------- the graph

_FILES = {}


def _all_files(root):
    """Every file under root, repo-relative (cached per root)."""
    if root not in _FILES:
        out = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
            for name in filenames:
                out.append(os.path.relpath(os.path.join(dirpath, name), root).replace(os.sep, "/"))
        _FILES[root] = out
    return _FILES[root]


def resolve_link(root, rel, target):
    """A Markdown link target → repo-relative path, or None when it is not a file link."""
    if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("#") or re.search(r"[<>{}]", target):
        return None  # a URL, an anchor here, or a template placeholder such as <repo>/
    path = target.split("#", 1)[0].split("?", 1)[0]
    path = re.sub(r":\d+(?:[-:]\d+)*$", "", path)  # `file.md:167` names a line, not a file
    if not path:
        return None
    if path.startswith("/"):
        joined = path.lstrip("/")
    else:
        joined = os.path.normpath(os.path.join(os.path.dirname(rel), path)).replace(os.sep, "/")
    if joined.startswith("../") or joined == "..":
        return None  # outside this repository: a sibling checkout, not looked at
    return joined


def build(root, cfg=None, today=None):
    cfg = cfg or load_config(root)
    today = today or datetime.date.today()
    _FILES.pop(root, None)
    rels = documents(root, cfg)
    dates = last_changed(root, rels)
    texts = {r: read(root, r) for r in rels}
    texts = {r: t for r, t in texts.items() if t is not None}
    project = os.path.basename(os.path.abspath(root))
    readme = texts.get("README.md", "")
    nodes, edges, findings, all_passages = {}, [], [], []
    pid = f"project:{project}"
    nodes[pid] = {"id": pid, "kind": "project", "area": "project",
                  "title": title_of(readme, project) if readme else project,
                  "pointer": "README.md#L1" if readme else None, "status": "active",
                  "source_at": dates.get("README.md")}
    defined = {}
    stale_days = int(cfg.get("stale_days", 90))
    tops = {r.split("/", 1)[0] for r in _all_files(root)}
    suffixes = _all_files(root)

    for rel, text in sorted(texts.items()):
        meta = front_matter(text)
        status = "active"
        head = "\n".join(text.splitlines()[:12])
        if meta.get("status", "").lower() in RETIRED or any(BANNER.match(l) for l in head.splitlines()):
            status = "superseded"
        did = f"doc:{rel}"
        nodes[did] = {"id": did, "kind": "document", "area": area_of(rel, cfg),
                      "title": title_of(text, rel), "pointer": f"{rel}#L1-L{max(1, len(text.splitlines()))}",
                      "status": status, "source_at": dates.get(rel)}
        edges.append({"src": did, "dst": pid, "kind": "about", "basis": "rule", "provenance": rel})
        # Stale facts: an expired valid_until, or an as_of older than stale_days.
        for key in ("valid_until", "expires"):
            v = meta.get(key)
            if v and re.match(r"\d{4}-\d{2}-\d{2}", v) and v[:10] < today.isoformat():
                nodes[did]["status"] = "stale"
                findings.append({"kind": "stale-fact", "severity": "fail", "where": f"{rel}#L1",
                                 "what": f"{key} {v[:10]} has passed", "fix": "re-verify against its source, "
                                 "then move the date, or mark the document superseded"})
        for key in ("as_of", "last_verified", "verified"):
            v = meta.get(key)
            if v and re.match(r"\d{4}-\d{2}-\d{2}", v):
                age = (today - datetime.date.fromisoformat(v[:10])).days
                if age > stale_days:
                    if nodes[did]["status"] == "active":
                        nodes[did]["status"] = "stale"
                    findings.append({"kind": "stale-fact", "severity": "warn", "where": f"{rel}#L1",
                                     "what": f"{key} {v[:10]} is {age} days old (limit {stale_days})",
                                     "fix": "re-verify against its source and move the date"})
        all_passages.extend(passages(rel, text))
        in_fence = False
        for n, line in enumerate(text.splitlines(), 1):
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            # An id is defined where it opens a table row or a heading.
            m = re.match(r"^\|\s*\**((?:[A-Z]{1,4})-\d{1,5})\**\s*\|(.*)", line)
            h = HEADING.match(line)
            hid = ID.match(h.group(2).strip("*` ")) if h else None
            new = m.group(1) if m and ID.fullmatch(m.group(1)) else (hid.group(1) if hid else None)
            if new and new not in defined:
                rest = (m.group(2) if m else h.group(2)).strip()
                cells = [c.strip(" *`") for c in rest.split("|") if c.strip(" *`")]
                label = next((c for c in cells if not re.fullmatch(r"[\d\- :]+", c)), "") if m else rest
                label = re.sub(r"^" + re.escape(new) + r"[\s:.—-]*", "", label)[:120]
                nid = f"id:{new}"
                defined[new] = rel
                nodes[nid] = {"id": nid, "kind": ID_KIND.get(new.split("-")[0], "record"),
                              "area": area_of(rel, cfg), "title": label or new,
                              "pointer": f"{rel}#L{n}", "status": "active", "source_at": dates.get(rel)}
                edges.append({"src": nid, "dst": did, "kind": "part-of", "basis": "fact",
                              "provenance": f"{rel}#L{n}"})
                continue
            for cid in ID.findall(line):
                edges.append({"src": did, "dst": f"id:{cid}", "kind": "cites", "basis": "rule",
                              "provenance": f"{rel}#L{n}"})
            for _label, target in LINK.findall(line):
                dst = resolve_link(root, rel, target)
                if dst is None:
                    continue
                if os.path.exists(os.path.join(root, dst)):
                    if dst.endswith(".md"):
                        edges.append({"src": did, "dst": f"doc:{dst}", "kind": "cites", "basis": "fact",
                                      "provenance": f"{rel}#L{n}"})
                else:
                    findings.append({"kind": "broken-link", "severity": "fail", "where": f"{rel}#L{n}",
                                     "what": f"link to {target} resolves to {dst}, which does not exist",
                                     "target": target, "fix": "heal --fix rewrites it when exactly one file "
                                     "of that name exists; otherwise point it at the new home or remove it"})
            for path, a, b in CITATION.findall(line):
                cpath = path if os.path.exists(os.path.join(root, path)) else \
                    os.path.normpath(os.path.join(os.path.dirname(rel), path)).replace(os.sep, "/")
                full = os.path.join(root, cpath)
                if not os.path.isfile(full):
                    if "/" in path and not any(f.endswith("/" + path) for f in suffixes):
                        # A citation may name another repository's path (the estate cites across
                        # repositories in prose), so a miss warns; a Markdown link here must open here.
                        ours = path.split("/", 1)[0] in tops
                        findings.append({"kind": "broken-citation", "severity": "warn",
                                         "where": f"{rel}#L{n}",
                                         "what": f"cites {path}:{a}, and {path} does not exist" +
                                         ("" if ours else " here (another repository's file?)"),
                                         "target": path, "fix": "point it at the file's new home, or name "
                                         "the repository it lives in"})
                    continue
                try:
                    with open(full, encoding="utf-8", errors="replace") as fh:
                        count = sum(1 for _ in fh)
                except OSError:
                    continue
                if int(b or a) > count:
                    findings.append({"kind": "stale-citation", "severity": "warn", "where": f"{rel}#L{n}",
                                     "what": f"cites {path}:{a}{'-' + b if b else ''}, and the file has {count} lines",
                                     "fix": "find the passage again and move the line numbers"})

    # Dangling ids and orphans.
    for e in edges:
        if e["kind"] == "cites" and e["dst"].startswith("id:") and e["dst"][3:] not in defined:
            findings.append({"kind": "dangling-id", "severity": "info", "where": e["provenance"],
                             "what": f"cites {e['dst'][3:]}, which no document here defines",
                             "fix": "define it, or say whose id it is (another project's ids are fine)"})
    inbound = {}
    for e in edges:
        if e["kind"] == "cites" and e["dst"].startswith("doc:") and e["src"] != e["dst"]:
            inbound.setdefault(e["dst"], set()).add(e["src"])
    entry = set(cfg.get("entry", []))
    for nid, node in nodes.items():
        if node["kind"] == "document" and nid[4:] not in entry and not inbound.get(nid) \
                and nid[4:] not in (BACKLOG_REL, README_REL):
            findings.append({"kind": "orphan", "severity": "warn", "where": f"{nid[4:]}#L1",
                             "what": "no document links to it; the map is its only way in",
                             "fix": "link it from the document it belongs to"})
    # Dated records are counted, never failed: they cite the tree as it was.
    for f in findings:
        if any(_glob_match(f["where"].split("#", 1)[0], h) or
               (h.startswith("**/") and f["where"].split("#", 1)[0].endswith(h[3:]))
               for h in cfg.get("history", [])) and f["severity"] == "fail":
            f["severity"] = "warn"
            f["what"] += " (dated record)"
    # One edge per (src, dst, kind): the first provenance wins.
    seen, uniq = set(), []
    for e in edges:
        key = (e["src"], e["dst"], e["kind"])
        if key not in seen:
            seen.add(key)
            uniq.append(e)
    rev = (git(root, "rev-parse", "--short", "HEAD") or "").strip() or None
    graph = {"schema": SCHEMA, "profile": PROFILE, "project": project, "revision": rev,
             "built_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
             "counts": {"documents": sum(1 for n in nodes.values() if n["kind"] == "document"),
                        "nodes": len(nodes), "edges": len(uniq), "passages": len(all_passages)},
             "nodes": sorted(nodes.values(), key=lambda n: n["id"]), "edges": uniq,
             "passages": all_passages, "findings": findings,
             "degraded": [] if rev else ["not a git checkout: dates are file times, no revision"]}
    return graph


def save(root, graph):
    d = os.path.join(root, INDEX_DIR)
    os.makedirs(d, exist_ok=True)
    tmp = os.path.join(d, "graph.json.tmp")
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(graph, fh, ensure_ascii=False, indent=1)
    os.replace(tmp, os.path.join(d, "graph.json"))


def load_or_build(root, write=True):
    graph = build(root)
    if write:
        save(root, graph)
    return graph


# ---------------------------------------------------------------- the map (committed)

def rel_from_map(target):
    return os.path.relpath(target, os.path.dirname(MAP_REL)).replace(os.sep, "/")


def render_map(root, graph):
    nodes = {n["id"]: n for n in graph["nodes"]}
    readme = read(root, "README.md") or ""
    lines = [GENERATED, "", f"# Documentation map: {graph['project']}", "",
             "The project's documentation as a graph: every document and every id it defines is a node, every "
             "link and citation an edge. Rebuild with `docgraph.py build`; search with `docgraph.py search`.",
             "", "## What the project is", ""]
    para = first_paragraph(readme)
    lines.append(f"{para} ([README.md]({rel_from_map('README.md')}))" if para else
                 "No README paragraph yet: the first thing a newcomer needs is one.")
    for kind, head in (("decision", "Decisions"), ("scenario", "Scenarios"), ("question", "Open questions")):
        items = [n for n in nodes.values() if n["kind"] == kind]
        lines += ["", f"## {head}", ""]
        if not items:
            lines.append("None recorded yet.")
        for n in sorted(items, key=lambda n: (n["pointer"].split("#")[0], _id_num(n["id"]))):
            path, _, anchor = n["pointer"].partition("#")
            lines.append(f"- [{n['id'][3:]}]({rel_from_map(path)}#{anchor.lower()}) {_md(n['title'])}")
    lines += ["", "## Documents by area", ""]
    by_area = {}
    for n in nodes.values():
        if n["kind"] == "document":
            by_area.setdefault(n["area"], []).append(n)
    for area in sorted(by_area):
        lines += [f"### {area}", ""]
        for n in sorted(by_area[area], key=lambda n: n["id"]):
            path = n["id"][4:]
            mark = "" if n["status"] == "active" else f" ({n['status']})"
            lines.append(f"- [{_md(n['title'])}]({rel_from_map(path)}){mark}")
        lines.append("")
    recheck = [f for f in graph["findings"] if f["kind"] in ("stale-fact", "stale-citation", "broken-citation")]
    lines += ["## Needs re-checking", ""]
    if not recheck:
        lines.append("Nothing found stale at this build.")
    for f in recheck:
        path, _, anchor = f["where"].partition("#")
        lines.append(f"- [{path}]({rel_from_map(path)}#{anchor.lower()}): {_md(f['what'])}")
    return "\n".join(lines).rstrip() + "\n"


def _id_num(nid):
    m = re.search(r"(\d+)$", nid)
    return int(m.group(1)) if m else 0


def _md(text):
    return re.sub(r"[\[\]]", "", str(text)).replace("—", ",")


def write_if_changed(root, rel, body):
    path = os.path.join(root, rel)
    old = read(root, rel)
    if old == body:
        return False
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(body)
    return True


# ---------------------------------------------------------------- healing and pruning

def heal(root, graph, fix=False):
    """Repairs what a machine can repair; returns (fixed, left)."""
    fixed, left = [], []
    names = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for name in filenames:
            rel = os.path.relpath(os.path.join(dirpath, name), root).replace(os.sep, "/")
            names.setdefault(name, []).append(rel)
    edits = {}
    for f in graph["findings"]:
        # Only links are repaired: a citation may name another repository's file, and rewriting it to a
        # same-named file here would change what the text claims.
        if f["kind"] == "broken-link" and fix and "(dated record)" not in f["what"]:
            path, _, anchor = f["where"].partition("#")
            target = f["target"]
            bare = target.split("#", 1)[0]
            line = re.search(r":(\d+)(?:[-:](\d+))*$", bare)
            bare = bare[:line.start()] if line else bare
            base = os.path.basename(bare)
            tail = bare.lstrip("./")
            # The file whose path ends with the target's own path wins (a root-relative link written
            # without its slash); else the one file of that name.
            if "/" in tail:
                cands = [c for c in _all_files(root) if c == tail or c.endswith("/" + tail)]
                parent = os.path.basename(os.path.dirname(tail))
                cands = cands or [c for c in names.get(base, [])
                                  if os.path.basename(os.path.dirname(c)) == parent]
            else:
                cands = names.get(base, [])
            if len(cands) == 1:
                new_abs = cands[0]
                if f["kind"] == "broken-link":
                    frag = "#" + target.split("#", 1)[1] if "#" in target else (f"#L{line.group(1)}" if line else "")
                    new = os.path.relpath(new_abs, os.path.dirname(path) or ".").replace(os.sep, "/") + frag
                else:
                    new = new_abs
                edits.setdefault(path, []).append((int(anchor[1:]), target, new, f))
                continue
        left.append(f)
    for path, changes in edits.items():
        full = os.path.join(root, path)
        with open(full, encoding="utf-8") as fh:
            lines = fh.read().split("\n")
        for n, old, new, f in changes:
            line = lines[n - 1]
            if f["kind"] == "broken-link":
                line = line.replace(f"]({old})", f"]({new})").replace(f"]({old} ", f"]({new} ")
            else:
                line = line.replace(f"`{old}:", f"`{new}:")
            if line != lines[n - 1]:
                lines[n - 1] = line
                fixed.append(dict(f, fixed=f"now points at {new}"))
            else:
                left.append(f)
        with open(full, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))
    return fixed, left


def prune(root, graph, apply=False):
    """Superseded documents outside docs/archive/: listed, or moved with their inbound links rewritten."""
    moved = []
    for n in graph["nodes"]:
        if n["kind"] != "document" or n["status"] != "superseded":
            continue
        src = n["id"][4:]
        if src in (README_REL, BACKLOG_REL) or src.startswith("docs/archive/"):
            continue
        dst = "docs/archive/" + (src[5:] if src.startswith("docs/") else src)
        moved.append((src, dst))
    if not apply:
        return moved
    for src, dst in moved:
        os.makedirs(os.path.dirname(os.path.join(root, dst)), exist_ok=True)
        if git(root, "mv", src, dst) is None:
            shutil.move(os.path.join(root, src), os.path.join(root, dst))
        for n in graph["nodes"]:
            if n["kind"] != "document":
                continue
            rel = n["id"][4:]
            if rel == src:
                continue
            text = read(root, rel)
            if text is None:
                continue

            def swap(m, rel=rel):
                target = m.group(2)
                if resolve_link(root, rel, target) == src:
                    frag = "#" + target.split("#", 1)[1] if "#" in target else ""
                    return f"[{m.group(1)}]({os.path.relpath(dst, os.path.dirname(rel) or '.')}{frag})"
                return m.group(0)
            new = LINK.sub(swap, text)
            if new != text:
                with open(os.path.join(root, rel), "w", encoding="utf-8") as fh:
                    fh.write(new)
    return moved


# ---------------------------------------------------------------- detect and refactoring backlog

def detect(root):
    """Is this project's documentation agent-ready? The hidden refactoring reads this."""
    cfg_present = os.path.isfile(os.path.join(root, CONFIG_REL))
    rels = documents(root, DEFAULT_CONFIG)
    beyond_readme = [r for r in rels if r != "README.md"]
    missing = []
    if not cfg_present:
        missing += ["graph", "search", "citations"]
    elif not os.path.isfile(os.path.join(root, MAP_REL)):
        missing.append("map")
    has_docs = bool(rels)
    return {"agent_ready": has_docs and not missing, "has_docs": has_docs,
            "documents": len(rels), "beyond_readme": len(beyond_readme), "missing": missing,
            "next": None if (not has_docs or not missing) else
            "python3 <skill>/scripts/docgraph.py init  (or: npx --yes task-pipeline-skill doc-graph init)"}


BACKLOG_HEAD = """# Refactoring backlog: documentation made agent-ready

Hidden refactoring (task-pipeline `references/doc-graph.md`): an agent that meets documentation an agent cannot
yet use (no graph, no citations, no search) converts it by the starter pack in small steps during its own task, and
leaves one row here. Rows are appended, never rewritten; a row that is done keeps its row and gets a state.

| Id | Date | Found | Done | Task | State |
|---|---|---|---|---|---|
"""


def refactor_note(root, what, did, task=None, today=None):
    today = (today or datetime.date.today()).isoformat()
    path = os.path.join(root, BACKLOG_REL)
    text = read(root, BACKLOG_REL) or BACKLOG_HEAD
    nums = [int(x) for x in re.findall(r"^\|\s*R-(\d+)\s*\|", text, re.M)]
    rid = f"R-{(max(nums) + 1) if nums else 1:03d}"
    cell = lambda s: str(s or "").replace("|", "/").replace("\n", " ").strip() or "-"
    row = f"| {rid} | {today} | {cell(what)} | {cell(did)} | {cell(task)} | {'done' if did else 'open'} |\n"
    if not text.endswith("\n"):
        text += "\n"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text + row)
    return rid


GRAPH_README = """# The documentation graph

This project's documentation is a graph (`knowledge-graph/1`, profile `starter`): every Markdown document and every
id it defines (`D-12`, `B-034`, `ADR-0001`, `S-3`) is a node; every link and every citation is an edge. Markdown stays
the source of truth; the graph is derived into `.docgraph/graph.json` (git-ignored) and rebuilt in a second.

| Do | Command |
|---|---|
| Rebuild the graph and [the map](MAP.md) | `docgraph.py build` |
| Find something, with the lines to cite | `docgraph.py search "how are releases tagged"` |
| Prove a quote before citing it | `docgraph.py cite "the exact words" docs/decisions.md` |
| See what a node links to and from | `docgraph.py neighbours D-12` |
| Find and repair broken links, stale facts, orphans | `docgraph.py heal` then `docgraph.py heal --fix` |
| Move superseded documents to `docs/archive/` | `docgraph.py prune` then `docgraph.py prune --apply` |
| Gate a change (exit 1 on a broken link or an expired fact) | `docgraph.py check` |

`docgraph.py` ships with the task-pipeline and evidence-docs skills (`scripts/docgraph.py`); without them,
`npx --yes task-pipeline-skill doc-graph <command>` runs the same file. Settings: [docgraph.json](docgraph.json).
Conversions of documentation that was not agent-ready are logged in [the refactoring backlog](../refactor-backlog.md).
"""


def init(root):
    created = []
    cfg_path = os.path.join(root, CONFIG_REL)
    if not os.path.isfile(cfg_path):
        os.makedirs(os.path.dirname(cfg_path), exist_ok=True)
        with open(cfg_path, "w", encoding="utf-8") as fh:
            json.dump(DEFAULT_CONFIG, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        created.append(CONFIG_REL)
    if write_if_changed(root, README_REL, GRAPH_README):
        created.append(README_REL)
    if not os.path.isfile(os.path.join(root, BACKLOG_REL)):
        write_if_changed(root, BACKLOG_REL, BACKLOG_HEAD)
        created.append(BACKLOG_REL)
    gi = os.path.join(root, ".gitignore")
    current = read(root, ".gitignore") or ""
    if not re.search(r"^/?\.docgraph/?$", current, re.M):
        with open(gi, "a", encoding="utf-8") as fh:
            fh.write(("" if not current or current.endswith("\n") else "\n") + ".docgraph/\n")
        created.append(".gitignore (.docgraph/)")
    graph = load_or_build(root)
    if write_if_changed(root, MAP_REL, render_map(root, graph)):
        created.append(MAP_REL)
    return created, graph


# ---------------------------------------------------------------- command line

def summary(graph):
    c = graph["counts"]
    by = {}
    for f in graph["findings"]:
        by[f["kind"]] = by.get(f["kind"], 0) + 1
    found = ", ".join(f"{k} {v}" for k, v in sorted(by.items())) or "none"
    return (f"graph {graph['schema']} ({graph['profile']}): {c['documents']} documents, {c['nodes']} nodes, "
            f"{c['edges']} edges, {c['passages']} passages; findings: {found}")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="docgraph.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    def add(name, **kw):
        p = sub.add_parser(name, **kw)
        p.add_argument("--root", default=".")
        return p
    add("init")
    add("build")
    p = add("check"); p.add_argument("--json", action="store_true")
    p.add_argument("--no-write", action="store_true", help="build in memory only (read-only audits)")
    p = add("heal"); p.add_argument("--fix", action="store_true")
    p = add("prune"); p.add_argument("--apply", action="store_true")
    p = add("search"); p.add_argument("query"); p.add_argument("-k", type=int, default=5)
    p.add_argument("--json", action="store_true")
    p = add("cite"); p.add_argument("quote"); p.add_argument("path")
    p = add("neighbours"); p.add_argument("id"); p.add_argument("--json", action="store_true")
    p = add("detect"); p.add_argument("--json", action="store_true")
    p = add("refactor-note"); p.add_argument("what"); p.add_argument("--did", default="")
    p.add_argument("--task", default="")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    if not os.path.isdir(root):
        die(f"--root {a.root} is not a directory")

    if a.cmd == "init":
        created, graph = init(root)
        print("created: " + (", ".join(created) if created else "nothing (already set up)"))
        print(summary(graph))
        return 0
    if a.cmd == "detect":
        d = detect(root)
        print(json.dumps(d, ensure_ascii=False) if a.json else
              ("agent-ready" if d["agent_ready"] else
               ("no documentation yet" if not d["has_docs"] else
                f"not agent-ready: missing {', '.join(d['missing'])}; next: {d['next']}")))
        return 0
    if a.cmd == "refactor-note":
        print(refactor_note(root, a.what, a.did, a.task))
        return 0
    if a.cmd == "cite":
        line = cite(root, a.quote, a.path)
        if line is None:
            print(f"not found: the quote does not stand verbatim in {a.path} (at least 12 characters)")
            return 1
        print(f"{a.path}#L{line}")
        return 0

    graph = load_or_build(root, write=not getattr(a, "no_write", False))
    if a.cmd == "build":
        write_if_changed(root, MAP_REL, render_map(root, graph)) if os.path.isfile(
            os.path.join(root, CONFIG_REL)) else None
        print(summary(graph))
        return 0
    if a.cmd == "check":
        fails = [f for f in graph["findings"] if f["severity"] == "fail"]
        if a.json:
            print(json.dumps({"ok": not fails, "counts": graph["counts"], "findings": graph["findings"],
                              "degraded": graph["degraded"]}, ensure_ascii=False, indent=1))
        else:
            for f in graph["findings"]:
                if f["severity"] != "info":
                    print(f"{f['severity']:4} {f['kind']:16} {f['where']}: {f['what']}")
            print(summary(graph))
            print("unlooked: links inside code fences, anchors within a file, external URLs")
        return 1 if fails else 0
    if a.cmd == "heal":
        fixed, left = heal(root, graph, fix=a.fix)
        for f in fixed:
            print(f"fixed  {f['kind']:16} {f['where']}: {f['fixed']}")
        for f in left:
            if f["severity"] != "info":
                print(f"left   {f['kind']:16} {f['where']}: {f['what']}; {f['fix']}")
        if a.fix:
            graph = load_or_build(root)
            if os.path.isfile(os.path.join(root, CONFIG_REL)):
                write_if_changed(root, MAP_REL, render_map(root, graph))
        print(f"fixed {len(fixed)}, left {sum(1 for f in left if f['severity'] != 'info')}"
              + ("" if a.fix else " (dry run: add --fix to repair)"))
        return 0
    if a.cmd == "prune":
        moved = prune(root, graph, apply=a.apply)
        for src, dst in moved:
            print(f"{'moved' if a.apply else 'would move'} {src} -> {dst}")
        if a.apply and moved:
            graph = load_or_build(root)
            if os.path.isfile(os.path.join(root, CONFIG_REL)):
                write_if_changed(root, MAP_REL, render_map(root, graph))
        print(f"{len(moved)} superseded document(s)" + ("" if a.apply else " (dry run: add --apply to move)"))
        return 0
    if a.cmd == "search":
        hits = search(graph, a.query, a.k)
        if a.json:
            print(json.dumps(hits, ensure_ascii=False, indent=1))
            return 0
        if not hits:
            print(f"no passage matches; searched {graph['counts']['passages']} passages")
        for h in hits:
            body = h["text"] if len(h["text"]) <= 400 else h["text"][:400].rsplit(" ", 1)[0] + " ..."
            print(f"{h['pointer']}  {h['title']}  (score {h['score']})\n  " + body.replace("\n", "\n  ") + "\n")
        return 0
    if a.cmd == "neighbours":
        key = a.id if ":" in a.id else (f"id:{a.id}" if ID.fullmatch(a.id) else f"doc:{a.id}")
        node = next((n for n in graph["nodes"] if n["id"] == key), None)
        out = [e for e in graph["edges"] if key in (e["src"], e["dst"])]
        if a.json:
            print(json.dumps({"node": node, "known": node is not None, "edges": out}, ensure_ascii=False, indent=1))
            return 0
        print(f"{key}: " + (f"{node['title']} ({node['pointer']})" if node else "known: false"))
        for e in out:
            arrow = f"-> {e['dst']}" if e["src"] == key else f"<- {e['src']}"
            print(f"  {e['kind']:8} {arrow}  [{e['basis']}] {e['provenance']}")
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
